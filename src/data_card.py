"""
data_card.py  (Phase 4)

Writes docs/data_card.md: what this dataset is, what it covers, what it doesn't,
its known biases, and what a model built on it must NOT be trusted to do.

Every number in the card is computed from the files on disk, so the card can't
drift out of date. The judgement calls (the "do not use for" list) are written
by hand, because those are a person's responsibility, not a script's.

Run (after build_ai_dataset.py and evaluate_phase4.py):
  python src/data_card.py
"""

import json
from pathlib import Path

import pandas as pd

AI = Path("data/ai_ready")
CARD = Path("docs/data_card.md")


def pct(x):
    return f"{x:.0%}" if x >= 0.01 else f"{x:.1%}"


def shares(series):
    """'outpatient 67%, emergency 27%, ...' including blanks."""
    counts = series.fillna("(blank)").value_counts(normalize=True)
    return ", ".join(f"{k} {pct(v)}" for k, v in counts.items())


def gate_detail(stage, check):
    report = json.loads((Path("data/quality") / f"gate_report_{stage}.json").read_text())
    return next(c["detail"] for c in report["checks"] if c["name"] == check)


def main():
    f = pd.read_csv(AI / "features.csv", dtype=str)
    manifest = json.loads((AI / "manifest.json").read_text())
    results = json.loads((AI / "eval_results.json").read_text())
    q = pd.read_csv("data/quarantine/encounters.csv")
    quarantined = f"{len(q)} encounters were quarantined** (" + ", ".join(
        f"{n} {reason.replace('_', ' ')}" for reason, n in q["quarantine_reason"].value_counts().items()) + ")"
    review_pairs = len(pd.read_csv("data/review/match_review_queue.csv"))

    acc = results["note_task"]["accuracy"]
    sizes = results["note_task"]["slice_sizes"]
    los = results["los_task"]["mae_days"]
    leak = results["cross_split_leakage"]
    by_source = pd.crosstab(f["source_system"], f["encounter_type"])
    er_only = all(by_source.loc[s, ["emergency", "inpatient"]].sum() == 0 for s in ["clinic_a", "clinic_b"])

    note_rows = "\n".join(
        f"| {name} | {r['all']:.1%} | {r['negation']:.1%} | {r['empty_note']:.1%} | {r['unseen_text']:.1%} |"
        for name, r in acc.items())
    los_rows = "\n".join(f"| {name} | {r['mae_all']} | {r['mae_inpatient']} |" for name, r in los.items())

    card = f"""# Data card: AI-Ready Health Data Pipeline dataset

_Generated by `python src/data_card.py`. Numbers come from the files on disk; edit the script, not this file._

> **Synthetic data only.** Every patient, note and date was made up by `src/generate_messy_data.py`.
> Nothing here describes real people, and no result here says anything about real patients.

## What it is

| | |
|---|---|
| Unit | one hospital or clinic **visit** |
| Visits | {manifest['visits']:,} from {manifest['patients']['train'] + manifest['patients']['eval']} patients (after matching, de-identification and quality gates) |
| Sources | 3 synthetic systems: two outpatient clinics and one emergency department |
| Split | by **patient**: train {manifest['patients']['train']} patients, eval {manifest['patients']['eval']} patients (no patient key on both sides) |
| Tasks | **A.** scrubbed diagnosis note → 1 of 6 categories · **B.** admission-time features → length of stay in days |
| Labels | the generator's ground truth. In a real hospital, chart review or ICD-10 codes, which are noisy. These are perfect. |
| Privacy | built only from the published de-identified tables: pseudonymous keys, 10-year age bands (90+ grouped), 3-digit ZIP, shifted dates, scrubbed notes |

## What it covers

- Sex: {shares(f['sex'])}
- Age at extract: {shares(f['age_band'])}
- Visit type: {shares(f['encounter_type'])}
- Source: {shares(f['source_system'])}
- Insurance: {shares(f['insurance'])}
- 3-digit ZIP: {shares(f['zip3'])} (south-east Pennsylvania and Delaware only)
- Diagnosis category: {shares(f['diagnosis_category'])}

## What it does NOT cover

- **Real clinical language.** Notes come from ~20 templates: only **{results['distinct_notes']} distinct notes** across {manifest['visits']:,} visits.
- Multiple diagnoses per visit, diagnosis codes (ICD-10), medications, labs, procedures, or outcomes.
- Any condition outside the 6 categories, and any visit type beyond outpatient, emergency and inpatient.
- Race, ethnicity, language, disability or income. Fairness across these groups **cannot be measured** with this data.
- Visits that failed cleaning: **{quarantined} and are not here. Visits with messy data are exactly the ones a model never sees.

## Known biases and quirks

1. **Diagnosis is independent of everything.** The generator picks the category at random, so a child is as likely to have type 2 diabetes as an 80-year-old, and chest pain is as common in a clinic as in the ER. Real prevalence is nothing like this.
2. **Source system decides visit type.** {"Only the ER system has emergency or inpatient visits." if er_only else "Visit type depends heavily on the source system."} A model can learn "ER = long stay" from `source_system` alone.
3. **Length of stay has no signal beyond visit type.** Outpatient and emergency visits are always 0 days by construction; inpatient stays are random 1-10 days.
4. **Birth dates are spread evenly from 1930 to 2024**, so older adults and children are over-represented compared with a real ER.
5. **The same real person can be on both sides of the split.** {leak['real_people_in_both_splits']} of {leak['real_people_with_visits']} real people have visits in both train and eval, because {review_pairs} possible duplicate pairs are still waiting in the human review queue. The patient-level split can only be as good as the matching.
6. **Re-identification risk is not zero.** Deid gate: {gate_detail('deid', 'k_anonymity')}.

## Baseline results (eval set)

### Task A: note → category (accuracy)

| Model | All (n={sizes['all']}) | Negation (n={sizes['negation']}) | Empty note (n={sizes['empty_note']}) | Text not in train (n={sizes['unseen_text']}) |
|---|---|---|---|---|
{note_rows}

- **The negation slice works:** "take the first diagnosis word" falls to {acc['first_keyword_mentioned']['negation']:.0%} on negated notes ("No hx of diabetes. BP elevated…"), and handling negation brings it back to {acc['first_keyword, negation_aware']['negation']:.0%}.
- **But the task is too easy.** Simple keyword rules get **{acc['most_keyword_hits']['all']:.1%}**, and every miss is an empty note. {results['eval_notes_seen_in_train']:.1%} of eval notes appear word for word in training, so a model that just memorises text scores {acc['memorizer (exact text lookup)']['all']:.1%}. **A high score on this eval set proves almost nothing about a real model.**
- Empty notes can't be classified by anyone. A model should say "unknown" there, not guess.

### Task B: length of stay (mean absolute error, days)

| Model | All (n={results['los_task']['sizes']['all']}) | Inpatient only (n={results['los_task']['sizes']['inpatient']}) |
|---|---|---|
{los_rows}

Knowing the visit type explains almost everything; adding age makes inpatient predictions **worse**. With {results['los_task']['sizes']['inpatient']} inpatient eval visits, any inpatient result is also too noisy to trust.

## A model built on this data must NOT be trusted to

- **Diagnose or triage real patients**, or support any clinical decision.
- Read **real clinical notes**: it has seen {results['distinct_notes']} templated sentences, not how clinicians actually write.
- **Predict length of stay** or plan beds and staffing: there is no signal to learn.
- Estimate **how common** any condition is, or how conditions relate to age, sex, insurance or place.
- Make any claim about **fairness** across race, ethnicity, language or income: those fields don't exist.
- Be judged by its score on this eval set alone. A high score here is expected even from a model that memorises.

## What this dataset IS good for

- Testing that a training pipeline runs end to end on governed, de-identified data.
- Teaching and demonstrating: patient-level splits, leakage, hard-case slices, label provenance, and why a data card matters.
- A smoke test before a model goes anywhere near real data, which would need its own governance, labels, eval set and card.

## What would make it trustworthy

Real (or realistic) notes with clinician-written variety; labels from coders with measured agreement; diagnoses that depend on age and setting; an eval set with text never seen in training; demographic fields to measure fairness; and the review queue resolved before splitting.
"""
    CARD.parent.mkdir(parents=True, exist_ok=True)
    CARD.write_text(card)
    print(f"Wrote {CARD}")


if __name__ == "__main__":
    main()
